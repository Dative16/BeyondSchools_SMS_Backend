def _protect_new_tables() -> None:
    """Row-level security and grants for the five new tables.

    Not optional, and not something to come back to: `student_health` holds
    sensitive personal data, and a table carrying school_id without a policy
    is a cross-tenant leak. The standing test in
    tests/integration/test_tenant_isolation.py compares pg_policies against
    app.models.TENANT_TABLES, so forgetting this fails a test rather than
    production.
    """
    role = f'"{settings.DB_APP_ROLE}"'
    predicate = "school_id = current_school() OR platform_scope()"

    for table in NEW_TENANT_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY {table}_tenant ON {table} "
            f"USING ({predicate}) WITH CHECK ({predicate})"
        )
        op.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {table} TO {role}")


